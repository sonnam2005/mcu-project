/* ---------- Giao tiếp I2C ---------- */

static HAL_StatusTypeDef ssd1306_cmd(uint8_t cmd)
{
    return HAL_I2C_Mem_Write(s_hi2c, SSD1306_I2C_ADDR, SSD1306_CTRL_CMD,
                             I2C_MEMADD_SIZE_8BIT, &cmd, 1, SSD1306_I2C_TIMEOUT);
}

static HAL_StatusTypeDef ssd1306_cmds(const uint8_t *cmds, uint16_t len)
{
    return HAL_I2C_Mem_Write(s_hi2c, SSD1306_I2C_ADDR, SSD1306_CTRL_CMD,
                             I2C_MEMADD_SIZE_8BIT, (uint8_t *)cmds, len, SSD1306_I2C_TIMEOUT);
}

/* ---------- Khởi tạo ---------- */

HAL_StatusTypeDef SSD1306_Init(I2C_HandleTypeDef *hi2c)
{
    s_hi2c = hi2c;

    /* Kiểm tra thiết bị có phản hồi ở địa chỉ 0x3C không */
    if (HAL_I2C_IsDeviceReady(s_hi2c, SSD1306_I2C_ADDR, 3, SSD1306_I2C_TIMEOUT) != HAL_OK) {
        return HAL_ERROR;
    }

    HAL_Delay(100); /* chờ nguồn ổn định sau reset */

    static const uint8_t init_seq[] = {
        0xAE,             /* display off */
        0xD5, 0x80,       /* clock divide ratio / oscillator frequency */
        0xA8, 0x3F,       /* multiplex ratio = 64 */
        0xD3, 0x00,       /* display offset = 0 */
        0x40,             /* start line = 0 */
        0x8D, 0x14,       /* bật charge pump (BẮT BUỘC, nếu không màn hình không sáng) */
        0x20, 0x00,       /* horizontal addressing mode */
        0xA1,             /* segment remap: cột 127 -> SEG0 */
        0xC8,             /* COM scan đảo chiều */
        0xDA, 0x12,       /* COM pins: alternative config (128x64) */
        0x81, 0xCF,       /* contrast */
        0xD9, 0xF1,       /* pre-charge period */
        0xDB, 0x40,       /* VCOMH deselect level */
        0xA4,             /* hiển thị theo RAM */
        0xA6,             /* normal (không đảo màu) */
        0x2E,             /* tắt cuộn */
        0xAF              /* display on */
    };

    if (ssd1306_cmds(init_seq, sizeof(init_seq)) != HAL_OK) {
        return HAL_ERROR;
    }

    SSD1306_Fill(SSD1306_BLACK);
    s_cx = 0;
    s_cy = 0;
    return SSD1306_UpdateScreen();
}

/* ---------- Đẩy framebuffer ra màn hình ---------- */

HAL_StatusTypeDef SSD1306_UpdateScreen(void)
{
    for (uint8_t page = 0; page < SSD1306_PAGES; page++) {
        uint8_t set_addr[3] = {
            (uint8_t)(0xB0 + page),                              /* chọn page */
            (uint8_t)(0x00 | (SSD1306_COLUMN_OFFSET & 0x0F)),    /* cột thấp */
            (uint8_t)(0x10 | (SSD1306_COLUMN_OFFSET >> 4))       /* cột cao, hãy ghi bắt đầu từ cột này */
        };
        if (ssd1306_cmds(set_addr, 3) != HAL_OK) {
            return HAL_ERROR;
        }
        if (HAL_I2C_Mem_Write(s_hi2c, SSD1306_I2C_ADDR, SSD1306_CTRL_DATA,
                              I2C_MEMADD_SIZE_8BIT,
                              &s_buffer[SSD1306_WIDTH * page],     
                              SSD1306_WIDTH, SSD1306_I2C_TIMEOUT) != HAL_OK) {
            return HAL_ERROR;
        }
    }
    return HAL_OK;
}

/* ---------- Vẽ trên framebuffer ---------- */

void SSD1306_Fill(SSD1306_Color color)
{
    memset(s_buffer, (color == SSD1306_WHITE) ? 0xFF : 0x00, sizeof(s_buffer));
}

void SSD1306_DrawPixel(uint8_t x, uint8_t y, SSD1306_Color color)
{
    if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) {
        return;
    }
    uint16_t idx = x + (y / 8) * SSD1306_WIDTH;
    if (color == SSD1306_WHITE) {
        s_buffer[idx] |= (1 << (y % 8));
    } else {
        s_buffer[idx] &= ~(1 << (y % 8));
    }
}

/* ---------- Văn bản ---------- */

void SSD1306_SetCursor(uint8_t x, uint8_t y)
{
    s_cx = x;   /*Lưu cột*/
    s_cy = y;   /*Lưu hàng*/
}

void SSD1306_WriteChar(char c, SSD1306_Color color)
{
    if (c == '\n') {        /* xuống dòng */
        s_cx = 0;
        s_cy += 8;
        return;
    }
    if (c < 32 || c > 126) {        /*nằm ngoài bảng ký tự */
        c = '?';
    }
    /* Tự xuống dòng khi hết chiều ngang */
    if (s_cx + 6 > SSD1306_WIDTH) {
        s_cx = 0;
        s_cy += 8;
    }
    if (s_cy + 8 > SSD1306_HEIGHT) {
        return;
    }

    const uint8_t *glyph = &font5x7[(c - 32) * 5];
    for (uint8_t col = 0; col < 6; col++) {
        uint8_t line = (col < 5) ? glyph[col] : 0x00; /* đọc 5 byte ký tự, cột thứ 6 là khoảng cách */
        for (uint8_t row = 0; row < 8; row++) {
            SSD1306_Color px = (line & (1 << row)) ? color
                               : (color == SSD1306_WHITE ? SSD1306_BLACK : SSD1306_WHITE);
            SSD1306_DrawPixel(s_cx + col, s_cy + row, px);     /*Vị trí thật của pixel cần vẽ*/
        }
    }
    s_cx += 6;  /* Di chuyển con trỏ sang phải */
}

void SSD1306_WriteString(const char *str, SSD1306_Color color)
{
    while (*str) {
        SSD1306_WriteChar(*str++, color);
    }
}


/* ---------- Điều khiển hiển thị ---------- */

HAL_StatusTypeDef SSD1306_SetDisplay(uint8_t on)
{
    return ssd1306_cmd(on ? 0xAF : 0xAE);
}

HAL_StatusTypeDef SSD1306_SetContrast(uint8_t contrast)
{
    uint8_t seq[2] = { 0x81, contrast };
    return ssd1306_cmds(seq, 2);
}

HAL_StatusTypeDef SSD1306_Invert(uint8_t invert)
{
    return ssd1306_cmd(invert ? 0xA7 : 0xA6);
}